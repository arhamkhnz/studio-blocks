import { access, mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { join, posix } from "node:path";
import { fileURLToPath } from "node:url";

const appDirectory = fileURLToPath(new URL("../", import.meta.url));
const sourceDirectory = "src/registry/blocks";
const previewDefaults = { colSpan: 1, rowSpan: 1, iframe: false };
const items = [];
const imports = [];
const gallery = [];
const names = new Set();

function getPreview(item) {
  const preview = { ...previewDefaults, ...item.meta?.preview };

  if (
    ![1, 2, 3].includes(preview.colSpan) ||
    !Number.isSafeInteger(preview.rowSpan) ||
    preview.rowSpan < 1 ||
    typeof preview.iframe !== "boolean"
  ) {
    throw new Error(`${item.name}: invalid meta.preview settings.`);
  }

  return preview;
}

async function writeGenerated(path, content) {
  try {
    if ((await readFile(path, "utf8")) === content) return;
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }

  await writeFile(path, content);
}

async function findBlocks(parent) {
  const directories = await readdir(join(appDirectory, parent), { withFileTypes: true });
  const found = [];

  for (const directory of directories) {
    if (!directory.isDirectory()) continue;
    const path = posix.join(parent, directory.name);
    let manifest;
    try {
      manifest = await readFile(join(appDirectory, path, "registry-item.json"), "utf8");
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
      found.push(...(await findBlocks(path)));
      continue;
    }
    found.push({ name: directory.name, path, manifest });
  }

  return found;
}

const directories = (await findBlocks(sourceDirectory))
  .map((directory) => {
    const item = JSON.parse(directory.manifest);
    const order = item.meta?.order ?? Number.MAX_SAFE_INTEGER;
    if (!Number.isSafeInteger(order) || order < 0) {
      throw new Error(`${directory.name}: meta.order must be a non-negative safe integer.`);
    }
    return { ...directory, item, order };
  })
  .sort((left, right) => left.order - right.order || left.name.localeCompare(right.name));

for (const directory of directories) {
  const item = directory.item;
  delete item.$schema;
  const component = item.meta?.component;
  const category = item.categories?.[0];

  if (item.name !== directory.name || typeof component !== "string" || !/^[A-Z][\w$]*$/.test(component)) {
    throw new Error(`${directory.name}: name must match its folder and meta.component must name the React export.`);
  }
  if (names.has(item.name)) throw new Error(`${item.name}: block names must be unique across categories.`);
  names.add(item.name);
  if (typeof category !== "string" || !category || category === "all") {
    throw new Error(`${item.name}: specify the gallery category in categories.`);
  }

  const files = [];
  for (const file of item.files ?? []) {
    const localPath = posix.normalize(file.path.replaceAll("\\", "/"));
    if (posix.isAbsolute(localPath) || localPath === ".." || localPath.startsWith("../")) {
      throw new Error(`${item.name}: file paths must stay inside the block folder.`);
    }
    const path = posix.join(directory.path, localPath);
    await access(join(appDirectory, path));
    files.push({ ...file, path });
  }

  const entryFile = files.find((file) => file.path.endsWith(".tsx"));
  if (!entryFile) throw new Error(`${item.name}: list the component entry first in files.`);

  const preview = getPreview(item);
  const examplePath = posix.join(directory.path, "example.tsx");
  let hasExample = false;
  try {
    await access(join(appDirectory, examplePath));
    hasExample = true;
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  const index = items.length;
  const importPath = (hasExample ? examplePath : entryFile.path).replace(/^src\//, "@/").replace(/\.tsx$/, "");
  const binding = hasExample ? `Block${index}` : `{ ${component} as Block${index} }`;
  imports.push(`import ${binding} from ${JSON.stringify(importPath)};`);
  gallery.push(`  {
    id: ${JSON.stringify(item.name)},
    title: ${JSON.stringify(item.title ?? item.name)},
    description: ${JSON.stringify(item.description ?? "")},
    category: ${JSON.stringify(category)},
    component: Block${index},
    colSpan: ${preview.colSpan},
    rowSpan: ${preview.rowSpan},
    iframe: ${preview.iframe},
  },`);
  items.push({ ...item, files });
}

const registry = `${JSON.stringify(
  {
    $schema: "https://ui.shadcn.com/schema/registry.json",
    name: "studio-blocks",
    homepage: "https://studio-blocks.arhamkhnz.com",
    items,
  },
  null,
  2,
)}\n`;

await writeGenerated(join(appDirectory, "registry.json"), registry);
await mkdir(join(appDirectory, "public/r"), { recursive: true });
await writeGenerated(join(appDirectory, "public/r/registry.json"), registry);

await writeGenerated(
  join(appDirectory, "src/features/gallery/catalog.ts"),
  `// Generated by scripts/generate-registry.mjs. Do not edit manually.
import type { GalleryBlock } from "@/features/gallery/types";
${imports.join("\n")}

export const blocks = [
${gallery.join("\n")}
] satisfies GalleryBlock[];
`,
);
